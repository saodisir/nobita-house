/**
 * The ten props of Nobita's bedroom, recovered verbatim from
 * `git show f129690:src/data/props.ts` (the `2f-nobita` block of the 2026-08 build).
 *
 * The `rodinPrompt` strings are the point of this file. They were written for these exact
 * objects and they are what a human pastes into the Hyper3D Rodin web UI, so they are kept
 * word for word — a paraphrase produces a different model. `build` records which of the two
 * pipelines an object goes through, which is the one thing the old data did not say and the
 * thing that now decides who does the work:
 *
 * - `blender` — straight edges, flat planes, repeating courses. Built procedurally, first in
 *   Blender and now by `src/editor/house/build-furniture.ts` in the browser.
 *   `docs/asset-pipeline.md` §3 records Rodin being rejected for exactly this class of geometry.
 * - `rodin` — soft, organic volume. Generated by hand in Rodin, then prepped in Blender.
 * - `shell` — part of the room itself, not an object placed in it.
 * - `character` — already shipped inside `public/models/characters/doraemon.glb`; reuse it
 *   rather than sculpting a second Doraemon.
 */

