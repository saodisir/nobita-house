export type PropBuild = 'blender' | 'rodin' | 'shell' | 'character';

export interface RoomProp {
  /** kebab-case, stable: the recovered ids, so the hotspot cards still resolve. */
  id: string;
  name: string;
  /** `[width, height, depth]` in metres, three.js Y-up. */
  size: [number, number, number];
  /** Verbatim from `f129690`. Never paraphrase: this is pasted into Rodin. */
  rodinPrompt: string;
  build: PropBuild;
  /** `RoomHotspot.id` this prop carries, if any. */
  hotspot?: string;
  /** Why this prop is on the pipeline it is on, where that is not obvious. */
  note?: string;
}

